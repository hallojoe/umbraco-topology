#!/usr/bin/env python3
"""Write ignored Claude Code and Codex MCP configurations for this topology."""
import json
import os
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
local = root / ".local" / "umbraco"
local.mkdir(parents=True, exist_ok=True)
credentials = root / ".local" / "credentials.env"


def read_credential(name: str) -> str:
    prefix = name + "="
    values = [line[len(prefix):] for line in credentials.read_text(encoding="utf-8").splitlines()
              if line.startswith(prefix)]
    if len(values) != 1 or not values[0].strip():
        raise ValueError(f"Missing or invalid local credential: {name}")
    return values[0]


client_id = read_credential("API_CLIENT_ID")
if not client_id.startswith("umbraco-back-office-") or client_id == "umbraco-back-office-":
    raise ValueError("API_CLIENT_ID must start with umbraco-back-office- and have a suffix")


profiles = json.loads((root / "Example.UmbracoSite.Web" / "Properties" / "launchSettings.json").read_text())
cm_url = profiles["profiles"]["SchedulingPublisher"]["environmentVariables"][
    "Umbraco__CMS__WebRouting__UmbracoApplicationUrl"].rstrip("/")
certificate = local / "devcert.pem"
if not certificate.exists():
    subprocess.run(
        ["dotnet", "dev-certs", "https", "--export-path", str(certificate), "--format", "Pem", "--no-password"],
        check=True,
    )
config = {
    "mcpServers": {
        "example-umbracosite": {
            "command": "node",
            "args": [str(root / "mcp" / "node_modules" / "@umbraco-cms" / "mcp-dev" / "dist" / "index.js")],
            "env": {
                "NODE_ENV": "production",
                "NODE_USE_SYSTEM_CA": "1",
                "NODE_EXTRA_CA_CERTS": os.environ.get("NODE_EXTRA_CA_CERTS", str(certificate)),
                "UMBRACO_BASE_URL": os.environ.get("UMBRACO_BASE_URL", cm_url),
                "UMBRACO_CLIENT_ID": client_id,
                "UMBRACO_CLIENT_SECRET": read_credential("API_CLIENT_SECRET"),
                "UMBRACO_INCLUDE_TOOL_COLLECTIONS": "document,media",
                "UMBRACO_ALLOWED_MEDIA_PATHS": str(local),
            },
        }
    }
}
server_name, server = next(iter(config["mcpServers"].items()))
codex_path = root / ".codex" / "config.toml"
header = "# Generated by scripts/configure-mcp.py; contains local credentials.\n"
if codex_path.exists() and not codex_path.read_text().startswith(header):
    raise RuntimeError("Existing .codex/config.toml is not generated by this script")

config_path = root / ".mcp.json"
config_path.write_text(json.dumps(config, indent=2) + "\n")
config_path.chmod(0o600)
codex_lines = [
    header,
    f'[mcp_servers.{json.dumps(server_name)}]\n',
    f'command = {json.dumps(server["command"])}\n',
    f'args = [{", ".join(json.dumps(arg) for arg in server["args"])}]\n',
    f'cwd = {json.dumps(str(root))}\n',
    f'\n[mcp_servers.{json.dumps(server_name)}.env]\n',
]
codex_lines += [f'{key} = {json.dumps(value)}\n' for key, value in server["env"].items()]
codex_path.parent.mkdir(parents=True, exist_ok=True)
codex_path.write_text("".join(codex_lines))
codex_path.chmod(0o600)
print("Wrote ignored .mcp.json and .codex/config.toml.")
